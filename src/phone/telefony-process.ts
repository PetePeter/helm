/**
 * Helm owns the telefony-app process: it writes the TOML from Helm settings,
 * launches `telefony-app <toml>`, and restarts it with capped backoff when it
 * exits or when the PhAP link declares it dead.
 */
import { spawn, type ChildProcess } from 'node:child_process';
import { EventEmitter } from 'node:events';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { normalizeNumber, type PhoneLineConfig } from './phone-config.js';

const q = (s: string) => JSON.stringify(s);

/** telefony.toml from Helm settings. The allowlist is every exact, non-blocked number with any switch on. */
export function renderTelefonyToml(cfg: PhoneLineConfig): string {
  const allow = [...new Set(cfg.contacts
    .filter((c) => c.role !== 'blocked' && !c.pattern.includes('*') && (c.callIn || c.callOut || c.smsIn || c.smsOut || c.conf))
    .map((c) => normalizeNumber(c.pattern, cfg.countryCode))
    .filter((n): n is string => n !== null))];
  const lines = [
    '# Generated by Helm (Settings > Phone line). Edits here are overwritten.',
    '[device]',
    `transport = ${q(cfg.transport)}`,
    '',
    '[policy]',
    `allowlist = [${allow.map(q).join(', ')}]`,
    // Helm's dial-out guard decides who may dial what; telefony must not second-guess it.
    'outbound = "all"',
    `country_code = ${q(cfg.countryCode)}`,
    `fallback_policy = ${q(cfg.ringFallback)}`,
    `ring_timeout_s = ${cfg.ringTimeoutS}`,
    '',
    '[phap]',
    `bind = ${q(`127.0.0.1:${cfg.port}`)}`,
    `token = ${q(cfg.token)}`,
    `heartbeat_s = ${cfg.heartbeatS}`,
    '',
    '[voice]',
    `tts = ${q(cfg.voice.tts)}`,
    ...(cfg.voice.piperModel ? [`piper_model = ${q(cfg.voice.piperModel)}`] : []),
    `stt_model = ${q(cfg.voice.sttModel)}`,
    '',
  ];
  return lines.join('\n');
}

export type TelefonyStatus =
  | { state: 'stopped' }
  | { state: 'running'; pid: number; since: number; restarts: number }
  | { state: 'backoff'; restartInMs: number; attempt: number; lastError: string }
  | { state: 'failed'; lastError: string };

export interface TelefonyProcessOptions {
  /** Where the generated TOML is written. */
  configPath: string;
  log?: (msg: string) => void;
  spawnFn?: typeof spawn;
  baseDelayMs?: number;
  maxDelayMs?: number;
  maxRestarts?: number;
  /** Uptime after which the restart counter resets. */
  stableMs?: number;
}

export class TelefonyProcess extends EventEmitter {
  private child: ChildProcess | null = null;
  private wanted = false;
  private attempt = 0;
  private timer: NodeJS.Timeout | null = null;
  private stableTimer: NodeJS.Timeout | null = null;
  private status: TelefonyStatus = { state: 'stopped' };
  private cfg: PhoneLineConfig | null = null;
  private stderrTail = '';
  /** Set while Helm itself kills the child, so its exit is not treated as a crash. */
  private killing = false;
  private ops: Promise<void> = Promise.resolve();

  /** start/stop/restart run one at a time. */
  private serial(fn: () => Promise<void>): Promise<void> {
    this.ops = this.ops.then(fn, fn);
    return this.ops;
  }

  constructor(private readonly opts: TelefonyProcessOptions) { super(); }

  getStatus(): TelefonyStatus { return this.status; }

  /** Write the TOML and (re)start. Restarts a running process so config changes apply. */
  start(cfg: PhoneLineConfig): Promise<void> {
    return this.serial(() => this.startNow(cfg));
  }

  private async startNow(cfg: PhoneLineConfig): Promise<void> {
    this.clearTimers();
    this.cfg = cfg;
    this.wanted = true;
    this.attempt = 0;
    await this.writeConfig(cfg);
    await this.killChild();
    this.launch();
  }

  stop(): Promise<void> {
    return this.serial(() => this.stopNow());
  }

  private async stopNow(): Promise<void> {
    this.wanted = false;
    this.clearTimers();
    await this.killChild();
    this.setStatus({ state: 'stopped' });
  }

  /** The link layer saw the process go silent: treat it like a crash. */
  restart(reason: string): Promise<void> {
    return this.serial(() => this.restartNow(reason));
  }

  private async restartNow(reason: string): Promise<void> {
    if (!this.wanted) return;
    this.opts.log?.(`telefony restart: ${reason}`);
    await this.killChild();
    this.scheduleRestart(reason);
  }

  private async writeConfig(cfg: PhoneLineConfig): Promise<void> {
    await fs.mkdir(path.dirname(this.opts.configPath), { recursive: true });
    await fs.writeFile(this.opts.configPath, renderTelefonyToml(cfg), 'utf8');
  }

  private launch(): void {
    if (!this.wanted || !this.cfg || this.child) return;
    const spawnFn = this.opts.spawnFn ?? spawn;
    let child: ChildProcess;
    try {
      child = spawnFn(this.cfg.executable, [this.opts.configPath], { windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
    } catch (err) {
      this.scheduleRestart(String(err));
      return;
    }
    this.child = child;
    this.stderrTail = '';
    child.stdout?.on('data', (d: Buffer) => this.opts.log?.(`telefony: ${d.toString().trimEnd()}`));
    child.stderr?.on('data', (d: Buffer) => {
      this.stderrTail = (this.stderrTail + d.toString()).slice(-400);
      this.opts.log?.(`telefony! ${d.toString().trimEnd()}`);
    });
    child.once('error', (err) => this.onExit(child, `spawn error: ${err.message}`));
    child.once('exit', (code, signal) => this.onExit(child, `exited (${signal ?? code})${this.stderrTail ? `: ${this.stderrTail.trim().split('\n').pop()}` : ''}`));
    if (child.pid) {
      this.setStatus({ state: 'running', pid: child.pid, since: Date.now(), restarts: this.attempt });
      this.stableTimer = setTimeout(() => { this.attempt = 0; }, this.opts.stableMs ?? 60_000);
    }
  }

  private onExit(child: ChildProcess, why: string): void {
    if (this.child !== child || this.killing) return;
    this.child = null;
    if (this.stableTimer) clearTimeout(this.stableTimer);
    if (!this.wanted) return;
    // telefony's fixed marker for any transport-open failure (missing dongle or a
    // wrong transport string). Retrying cannot fix either, so stop and say so.
    if (this.stderrTail.includes('telefony-app: dongle not found')) {
      this.setStatus({ state: 'failed', lastError: 'Bluetooth dongle not found: check it is plugged in and the transport setting, then press Restart' });
      return;
    }
    this.scheduleRestart(why);
  }

  private scheduleRestart(lastError: string): void {
    this.clearTimers();
    if (!this.cfg?.watchdog || this.attempt >= (this.opts.maxRestarts ?? 10)) {
      this.setStatus({ state: 'failed', lastError });
      return;
    }
    const delay = Math.min((this.opts.baseDelayMs ?? 1000) * 2 ** this.attempt, this.opts.maxDelayMs ?? 60_000);
    this.attempt += 1;
    this.setStatus({ state: 'backoff', restartInMs: delay, attempt: this.attempt, lastError });
    this.timer = setTimeout(() => this.launch(), delay);
  }

  private async killChild(): Promise<void> {
    const child = this.child;
    if (!child) return;
    if (this.stableTimer) clearTimeout(this.stableTimer);
    if (child.exitCode !== null || child.signalCode !== null) { this.child = null; return; }
    // `this.child` stays set until it has exited, so a launch() cannot start a second one.
    this.killing = true;
    const exited = await new Promise<boolean>((resolve) => {
      const done = setTimeout(() => {
        try { child.kill('SIGKILL'); } catch { /* already gone */ }
        resolve(child.exitCode !== null || child.signalCode !== null);
      }, 3000);
      child.once('exit', () => { clearTimeout(done); resolve(true); });
      try { child.kill(); } catch { /* exit or timeout settles it */ }
    });
    this.killing = false;
    if (!exited) this.opts.log?.(`telefony pid ${child.pid} did not exit after SIGKILL`);
    if (this.child === child) this.child = null;
  }

  private clearTimers(): void {
    if (this.timer) clearTimeout(this.timer);
    if (this.stableTimer) clearTimeout(this.stableTimer);
    this.timer = null;
  }

  private setStatus(s: TelefonyStatus): void {
    this.status = s;
    this.emit('status', s);
  }
}
